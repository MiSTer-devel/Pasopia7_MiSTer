#!/usr/bin/env python3
"""Generate rtl/p7_kbd_table.svh from the Common Source Code Project's Pasopia 7 key matrix.

    tools/gen_kbd_table.py ../common_source_code/src/vm/pasopia7/keyboard.cpp > rtl/p7_kbd_table.svh
    tools/gen_kbd_table.py --paso ../common_source_code/src/vm/pasopia/keyboard.cpp > rtl/paso_kbd_table.svh

--paso: the original Pasopia's matrix (function paso_key). It has real Down, Insert and arrow positions, so only
Backspace -> DEL is folded; ESC sits on two positions (row 3 bits 1 and 3): the table gives bit 3, p7_kbd.sv mirrors
it to bit 1.

CSCP's key_map[12][8] gives, for each of the 12 rows (PIO port A: bits 6-4 pick a group of four rows, bits 3-0 the
rows in it) and 8 return bits (PIO port B, active low), the Windows virtual key on a Japanese keyboard. Each virtual
key maps here to the PS/2 set 2 codes of the same key position (US and JP 106 keyboards). CSCP also folds four PC
keys onto Pasopia keys, which the table keeps:
    Backspace -> DEL,  Insert -> SHIFT + DEL,  Down -> SHIFT + UP,  Tab -> SHIFT + ESC.

Output: function p7_key(input [8:0] ps2) returning {valid, extra_shift, row[3:0], bit[2:0]} (9 bits).
"""
import re
import sys

E0 = 0x100
VK2PS2 = {
    0x12: [0x11],                     # GRAPH: left Alt
    0x10: [0x12, 0x59],               # SHIFT: both shifts
    0x14: [0x58],                     # CAPS
    0x11: [0x14, E0 | 0x14],          # CTRL: both ctrls
    0x15: [0x13, E0 | 0x11],          # KANA: JP kana key, right Alt
    0x60: [0x70], 0x61: [0x69], 0x62: [0x72], 0x63: [0x7A], 0x64: [0x6B],
    0x65: [0x73], 0x66: [0x74], 0x67: [0x6C], 0x68: [0x75], 0x69: [0x7D],
    0x6A: [0x7C], 0x6B: [0x79], 0x6D: [0x7B], 0x6E: [0x71], 0x6F: [E0 | 0x4A],
    0x0D: [0x5A, E0 | 0x5A],          # RETURN: main and keypad Enter
    0x27: [E0 | 0x74], 0x25: [E0 | 0x6B], 0x26: [E0 | 0x75], 0x28: [E0 | 0x72], 0x2D: [E0 | 0x70],
    0x7A: [0x78],                     # F11 (LABEL in MAME's names)
    0x2E: [E0 | 0x71],                # DEL
    0x1B: [0x76],                     # ESC
    0x24: [E0 | 0x6C],                # HOME/CLS
    0xE5: [0x07],                     # VK_PROCESSKEY in CSCP's table (KANJI key in MAME): F12
    0x78: [0x01], 0x79: [0x09],       # F9, F10 (COPY, STOP in MAME's names)
    0x20: [0x29],
    0x70: [0x05], 0x71: [0x06], 0x72: [0x04], 0x73: [0x0C],
    0x74: [0x03], 0x75: [0x0B], 0x76: [0x83], 0x77: [0x0A],
    0x31: [0x16], 0x32: [0x1E], 0x33: [0x26], 0x34: [0x25], 0x35: [0x2E],
    0x36: [0x36], 0x37: [0x3D], 0x38: [0x3E], 0x39: [0x46], 0x30: [0x45],
    0x41: [0x1C], 0x42: [0x32], 0x43: [0x21], 0x44: [0x23], 0x45: [0x24], 0x46: [0x2B], 0x47: [0x34],
    0x48: [0x33], 0x49: [0x43], 0x4A: [0x3B], 0x4B: [0x42], 0x4C: [0x4B], 0x4D: [0x3A], 0x4E: [0x31],
    0x4F: [0x44], 0x50: [0x4D], 0x51: [0x15], 0x52: [0x2D], 0x53: [0x1B], 0x54: [0x2C], 0x55: [0x3C],
    0x56: [0x2A], 0x57: [0x1D], 0x58: [0x22], 0x59: [0x35], 0x5A: [0x1A],
    0xBD: [0x4E],                     # - =
    0xDE: [0x55],                     # ^ ~   (US = +)
    0xDC: [0x6A, 0x0E],               # yen | (JP yen key; US backtick)
    0xC0: [0x54],                     # @ `   (US [)
    0xDB: [0x5B],                     # [ {   (US ])
    0xBB: [0x4C],                     # ; +
    0xBA: [0x52],                     # : *   (US ')
    0xDD: [0x5D],                     # ] }   (JP ] key; US backslash)
    0xBC: [0x41], 0xBE: [0x49], 0xBF: [0x4A],
    0xE2: [0x51, 0x61],               # \ _   (JP ro key; ISO 102nd key)
}
FOLDED = {   # PS/2 code -> (VK it stands for, with SHIFT)
    0x66: (0x2E, False),              # Backspace -> DEL
    E0 | 0x70: (0x2E, True),          # Insert -> SHIFT + DEL
    E0 | 0x72: (0x26, True),          # Down -> SHIFT + UP
    0x0D: (0x1B, True),               # Tab -> SHIFT + ESC
}

paso = sys.argv[1] == '--paso'
if paso:
    del sys.argv[1]
    FOLDED = {0x66: (0x2E, False)}
fn = 'paso_key' if paso else 'p7_key'
src = open(sys.argv[1], encoding='latin-1').read()
body = src[src.index('key_map[12][8]'):]
body = body[:body.index('};')]
rows = re.findall(r'\{([^{}]*)\}', body)
assert len(rows) == 12, len(rows)
pos = {}
for r, line in enumerate(rows):
    vks = [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', line)]
    assert len(vks) == 8
    for b, vk in enumerate(vks):
        if vk:
            assert vk not in pos or (paso and vk == 0x1B), hex(vk)
            pos[vk] = (r, b)

entries = {}
for vk, (r, b) in pos.items():
    for p in VK2PS2[vk]:
        assert p not in entries, hex(p)
        entries[p] = (False, r, b, vk)
for p, (vk, sh) in FOLDED.items():
    assert p not in entries, hex(p)
    r, b = pos[vk]
    entries[p] = (sh, r, b, vk)

machine = 'pasopia' if paso else 'pasopia7'
out = [f'// Generated by tools/gen_kbd_table.py from CSCP src/vm/{machine}/keyboard.cpp key_map. Do not edit.',
       f'// {fn}: PS/2 {{E0, code}} -> {{valid, extra SHIFT, row[3:0], return bit[2:0]}}.',
       f'function automatic [8:0] {fn}(input [8:0] k);',
       '\tcase (k)']
for p in sorted(entries):
    sh, r, b, vk = entries[p]
    out.append(f"\t9'h{p:03x}: {fn} = {{1'b1, 1'b{int(sh)}, 4'd{r}, 3'd{b}}};   // VK {vk:02X}")
out += [f"\tdefault: {fn} = 9'd0;", '\tendcase', 'endfunction']
print('\n'.join(out))
